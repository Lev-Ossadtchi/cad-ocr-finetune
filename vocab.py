#!/usr/bin/env python3
"""Словарь подписей, какие встречаются на чертежах наружных сетей.

Строки не выдуманы из головы: это форматы записи из ГОСТ 21.604, ТУ
производителей труб и типовых альбомов колодцев. Ради воспроизводимости всё
собирается из шаблонов, а не берётся из чужих файлов: чертежи заказчиков
конфиденциальны и в этот репозиторий не попадают ни строкой.

Разбиение train/val/test идёт по шаблонам, а не по готовым строкам: иначе одна
и та же запись с другим диаметром попадёт и в обучение, и в тест, и замер
покажет не работу модели, а память.
"""
import random

CORRUGATED = [110, 160, 200, 250, 315, 400, 500, 630, 800, 1000, 1200]
PE_SIZES = [(32, "2,0"), (40, "2,4"), (63, "3,8"), (90, "5,4"), (110, "6,6"),
            (160, "9,5"), (225, "13,4"), (315, "18,7"), (710, "42,1")]
SDR = [11, 17, 21, 26]
SN = [2, 4, 8, 16]
WELLS = ["КСЛ", "КСП", "КСУ1", "КСЧ1", "КС", "КЦД", "ДК"]
NETS = ["К1", "К2", "К3", "В1", "В2", "В3", "Т1", "Т2"]

TEMPLATES = {
    # шаблон -> как собрать строку
    "труба_гофра":   lambda r: (f"Труба {r.choice(['КОРСИС', 'КОРСИС ПРО', 'ИЗОКОРСИС'])} "
                                f"SN{r.choice(SN)} DN/OD {r.choice(CORRUGATED)} "
                                f"ТУ 22.21.21-001-73011750-2021"),
    "труба_пэ":      lambda r: (lambda d, w: f"Труба ПЭ100/ПЭ100-RC ВОДА SDR{r.choice(SDR)}-{d}х{w} "
                                             f"ГОСТ Р 70628.2-2023")(*r.choice(PE_SIZES)),
    "муфта":         lambda r: (f"Муфта КОРСИС DN/OD {r.choice(CORRUGATED)} "
                                f"с двумя уплотнительными кольцами"),
    "колодец":       lambda r: f"{r.choice(WELLS)}-{r.randint(1, 20)}",
    # Метка сети не случайна: у канализации это К, у водопровода В, у тепла Т.
    # Случайная пара вроде «Канализация бытовая В2» на чертеже не встречается,
    # и учить модель на несуществующих сочетаниях незачем.
    "сеть":          lambda r: r.choice([
        f"Канализация бытовая К{r.randint(1, 3)}",
        f"Канализация дождевая К{r.randint(1, 3)}",
        f"Водопровод хозяйственно-питьевой В{r.randint(1, 3)}",
        f"Водопровод противопожарный В{r.randint(1, 3)}",
        f"Теплотрасса Т{r.randint(1, 2)}"]),
    "отметка":       lambda r: f"{r.randint(100, 400)},{r.randint(0, 99):02d}",
    "длина":         lambda r: f"{r.randint(1, 250)},{r.randint(0, 99):02d}",
    "уклон":         lambda r: f"i={r.randint(2, 40)/1000:.3f}".replace(".", ","),
    "номер_узла":    lambda r: f"У-{r.randint(1, 30)}",
    "гост":          lambda r: f"ГОСТ {r.randint(1000, 33000)}-{r.choice(list(range(60, 100)) + list(range(1, 26))):02d}",
    "позиция":       lambda r: f"{r.randint(1, 40)}. поз. {r.randint(1, 40)}",
    "глубина":       lambda r: f"{r.randint(1000, 6000)}",
    "высота_плюс":   lambda r: f"{r.randint(500, 2500)}+{r.choice([50, 100, 150])}",
    "объём":         lambda r: f"0,{r.randint(10, 99)}",
    "скобы":         lambda r: f"{r.randint(1, 9)} скоб{r.choice(['а', 'ы', ''])}",
    "люк":           lambda r: r.choice(["Л", "ЛУ", "т", "ТМ", "ДБ", "Л-В"]),
    # Примечания под таблицами — единственное место на чертеже, где строчных
    # букв много и подряд. Без них модель училась читать только прописные и на
    # слове «уплотнительными» выдавала «УПЛОТНИТЕЛЫНЫМИ»: строчных она в
    # обучении почти не видела. Фразы собираются из кусков, а не копируются
    # из чужих чертежей.
    "примечание":    lambda r: (
        f"{r.randint(1, 5)}. {r.choice(NOTE_HEAD)} {r.choice(NOTE_TAIL)}"),
    "основание":     lambda r: (f"{r.choice(['Грунтовое плоское', 'Песчаное плоское', 'Щебёночное'])} "
                                f"с подготовкой из {r.choice(['песчаного', 'щебёночного'])} грунта "
                                f"(h=0,{r.randint(10, 30)} м)"),
    "равенство":     lambda r: r.choice([
        f"i={r.randint(2, 40)/1000:.3f}".replace(".", ","),
        f"h={r.randint(1, 9)},{r.randint(0, 99):02d} м",
        f"L={r.randint(10, 400)},{r.randint(0, 99):02d} м",
        f"Dу={r.choice(CORRUGATED)} мм"]),
}

NOTE_HEAD = [
    "Люки колодцев на незастроенных территориях возвышаются",
    "Вокруг люков колодцев предусматривается отмостка",
    "Колодцы приняты по типовому альбому",
    "Трубы укладываются на основание",
    "Деталировка колодцев представлена",
    "Глубина заложения трубопровода принята",
]
NOTE_TAIL = [
    "над поверхностью земли не менее чем на 0,2 м.",
    "шириной 0,5 м с уклоном не менее 1,0 % от крышки люка.",
    "с подготовкой из песчаного грунта толщиной 150 мм.",
    "ниже глубины промерзания грунта.",
    "на отдельном листе настоящего раздела.",
    "по согласованию с эксплуатирующей организацией.",
]

# По шаблонам, а не по строкам: тестовые шаблоны в обучение не попадают вовсе.
TEST_TEMPLATES = ["муфта", "сеть", "уклон", "высота_плюс", "скобы"]
# «примечание» и «основание» — обучающие: там строчные буквы, которых в
# остальных шаблонах почти нет, и без них модель забывает нижний регистр.
VAL_TEMPLATES = ["колодец", "гост", "объём"]
TRAIN_TEMPLATES = [k for k in TEMPLATES if k not in TEST_TEMPLATES + VAL_TEMPLATES]


def sample(split, n, seed=0):
    """n подписей выбранного разбиения. Дубли убираются: одинаковые строки
    в выборке завышают точность, если модель угадала одну из них."""
    r = random.Random(seed)
    keys = {"train": TRAIN_TEMPLATES, "val": VAL_TEMPLATES, "test": TEST_TEMPLATES}[split]
    out, seen = [], set()
    guard = 0
    while len(out) < n and guard < n * 200:
        guard += 1
        k = r.choice(keys)
        s = TEMPLATES[k](r)
        if s not in seen:
            seen.add(s)
            out.append((k, s))
    return out


if __name__ == "__main__":
    for split in ("train", "val", "test"):
        got = sample(split, 6, seed=1)
        print(f"{split}:")
        for k, s in got:
            print(f"   [{k}] {s}")
